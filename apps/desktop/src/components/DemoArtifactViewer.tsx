export const DemoArtifactViewer: React.FC<DemoArtifactViewerProps> = ({
  className = "",
  onDimensionsReady,
  defaultArtifact = "svg",
  showSwitcher = true,
}) => {
  const [activeArtifact, setActiveArtifact] = useState<"svg" | "html">(defaultArtifact);
  const containerRef = React.useRef<HTMLDivElement>(null);

  React.useEffect(() => {
    if (containerRef.current && onDimensionsReady) {
      const rect = containerRef.current.getBoundingClientRect();
      onDimensionsReady({ width: rect.width, height: rect.height });
    }
  }, [onDimensionsReady]);

  const sanitizedSvg = React.useMemo(() => sanitizeSvg(SOLAR_SYSTEM_SVG), []);
  const sandboxedHtml = React.useMemo(() => generateSandboxedHtml(ANIMATED_CARD_HTML), []);

  return (
    <div
      ref={containerRef}
      className={`relative w-full h-full flex flex-col items-center justify-center overflow-hidden bg-[#070B14] rounded-lg ${className}`}
    >
      {/* Switcher tabs */}
      {showSwitcher && (
        <div className="absolute top-2 right-2 z-20 flex items-center gap-1 bg-slate-900/90 p-1 rounded-lg border border-slate-700/80 backdrop-blur-sm pointer-events-auto">
          <button
            onClick={() => setActiveArtifact("svg")}
            className={`px-2 py-0.5 text-[11px] font-medium rounded transition-colors ${
              activeArtifact === "svg"
                ? "bg-blue-600 text-white"
                : "text-slate-400 hover:text-white"
            }`}
          >
            SVG Demo
          </button>
          <button
            onClick={() => setActiveArtifact("html")}
            className={`px-2 py-0.5 text-[11px] font-medium rounded transition-colors ${
              activeArtifact === "html"
                ? "bg-blue-600 text-white"
                : "text-slate-400 hover:text-white"
            }`}
          >
            HTML Sandbox
          </button>
        </div>
      )}

      {activeArtifact === "svg" ? (
        <div
          className="w-full h-full flex items-center justify-center p-2"
          dangerouslySetInnerHTML={{ __html: sanitizedSvg }}
        />
      ) : (
        <iframe
          srcDoc={sandboxedHtml}
          sandbox="allow-scripts"
          className="w-full h-full border-0 pointer-events-none"
          title="VisualLoop Sandboxed HTML Preview"
        />
      )}
    </div>
  );
};
