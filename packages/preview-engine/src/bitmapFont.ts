/**
 * Returns true if pixel (col, row) is active for the character.
 * col: 0..4 (left to right)
 * row: 0..6 (top to bottom)
 */
export function isFontPixelActive(char: string, col: number, row: number): boolean {
  if (col < 0 || col >= 5 || row < 0 || row >= 7) return false;
  const glyph = FONT_5X7[char] || FONT_5X7["?"] || [0, 0, 0, 0, 0, 0, 0];
  const rowBits = glyph[row] ?? 0;
  // Bit 4 is col 0, Bit 0 is col 4
  const mask = 1 << (4 - col);
  return (rowBits & mask) !== 0;
}
